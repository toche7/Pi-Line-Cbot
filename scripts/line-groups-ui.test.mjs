import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:http';
import { LineGroupStore, LineGroupService } from '../dist/line-groups.js';
import { adminHandler } from '../dist/admin.js';
import { ConversationMonitor } from '../dist/monitor.js';
import { CourseRequestStore } from '../dist/course-requests.js';
import { CustomerStore } from '../dist/customers.js';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = mkdtempSync(join(tmpdir(), 'line-groups-ui-'));
const rooms = new LineGroupStore(join(root, 'rooms'), 'fixture-oa'), groupId = 'C' + 'a'.repeat(32);
rooms.observe({ groupId, type: 'message', eventId: 'fixture-event', at: new Date().toISOString(), text: '<img src=x onerror=alert(1)> ข้อความห้องทดสอบใน temp' });
const service = new LineGroupService(rooms, 'fixture-token', async () => new Response(JSON.stringify({ groupId, groupName: 'ห้อง LINE ตัวอย่างใน temp' })));
const monitor = new ConversationMonitor(join(root, 'monitor')), requests = new CourseRequestStore(join(root, 'requests')), customers = new CustomerStore(join(root, 'customers'));
const server = createServer(adminHandler(monitor, requests, customers, undefined, undefined, undefined, undefined, undefined, service));
let browser;
try {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:' + server.address().port + '/#monitor');
  await page.locator('#line-rooms summary').click();
  await page.locator('#line-rooms-list button').first().click();
  assert.equal(await page.locator('#line-rooms-heading').textContent(), 'ห้อง LINE ตัวอย่างใน temp');
  assert.ok((await page.locator('#line-rooms-mode').textContent()).includes('อ่านอย่างเดียว'));
  await page.locator('#line-rooms-messages').getByText('<img src=x onerror=alert(1)> ข้อความห้องทดสอบใน temp', { exact: true }).waitFor();
  assert.equal(await page.locator('#line-rooms-messages img').count(), 0);
  assert.equal(await page.locator('#line-rooms textarea').count(), 0);
  await page.getByRole('button', { name: 'อัปเดตชื่อห้องจาก LINE', exact: true }).click();
  await page.waitForFunction(() => !document.getElementById('line-rooms-refresh-name').disabled);
  await page.getByLabel('ค้นหาห้อง LINE', { exact: true }).fill('ไม่มีห้องชื่อนี้');
  assert.equal(await page.locator('#line-rooms-list button').count(), 0);
  await page.getByLabel('ค้นหาห้อง LINE', { exact: true }).fill('');
  rooms.enableMentions(groupId);
  rooms.reserveReply(groupId, 'fixture-reply');
  rooms.finishReply(groupId, 'fixture-reply', 'คำตอบ fixture เมื่อถูกแท็ก', 'accepted');
  await page.getByRole('button', { name: 'โหลดห้องล่าสุด', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('line-rooms-mode').textContent.includes('ตอบเฉพาะเมื่อแท็ก'));
  await page.locator('#line-rooms-messages').getByText('คำตอบ fixture เมื่อถูกแท็ก', { exact: true }).waitFor();
  rooms.enableCallWord(groupId);
  await page.getByRole('button', { name: 'โหลดห้องล่าสุด', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('line-rooms-mode').textContent.includes('พิมพ์ CBOT'));
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.equal(customers.snapshot({ events: [], requests: [] }).customers.length, 0);
  assert.equal(monitor.snapshot().events.length, 0); assert.equal(requests.list().length, 0);
  assert.deepEqual(errors, []);
  console.log('PASS room browser: name, messages, XSS escaping, refresh, search, mobile, no send controls; no customers, consent, direct history or jobs added. Temp fixtures only.');
} finally {
  if (browser) await browser.close();
  server.closeAllConnections(); await new Promise(resolve => server.close(resolve));
  rmSync(root, { recursive: true, force: true });
}
