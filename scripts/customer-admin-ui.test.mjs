// Run after npm run build. All customer writes use a temporary directory.
// PLAYWRIGHT_MODULE may point at the desktop bundled playwright/index.mjs.
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtempSync, rmSync, readFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { CustomerStore } from '../dist/customers.js';
import { ConversationMonitor } from '../dist/monitor.js';
import { CourseRequestStore, CourseRequests } from '../dist/course-requests.js';
import { adminHandler } from '../dist/admin.js';
import { LineProfiles } from '../dist/line-profile.js';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = mkdtempSync(join(tmpdir(), 'cbtu-customer-ui-'));
const monitor = new ConversationMonitor(join(root, 'monitor'));
const requests = new CourseRequestStore(join(root, 'requests'));
const store = new CustomerStore(join(root, 'customers'));
monitor.record({ id: 'ui-fixture', account: 'test-oa', userId: 'UI-fixture-only', direction: 'in', text: 'ข้อความทดสอบใน temp เท่านั้น', status: 'received', at: new Date().toISOString() });
monitor.record({ id: 'ui-fixture-two', account: 'test-oa', userId: 'UI-second-only', direction: 'in', text: 'อีกหนึ่งข้อความทดสอบใน temp', status: 'received', at: new Date().toISOString() });
const lineUser = 'U' + 'a'.repeat(32);
monitor.record({ id: 'ui-line-name', account: 'test-oa', userId: lineUser, direction: 'in', text: 'fixture สำหรับชื่อ LINE ใน temp', status: 'received', at: new Date().toISOString() });
const requestFlow = new CourseRequests(requests), owner = { channel: 'line', scope: 'test-oa:direct', user: 'UI-fixture-only' };
const preview = requestFlow.handle(owner, '/contact เรื่องทดสอบ UI ใน temp เท่านั้น');
requestFlow.handle(owner, '/confirm-request ' + preview.match(/confirm-request ([A-F0-9]+)/)[1]);
const monitorBefore = readFileSync(join(root, 'monitor/monitor.json'), 'utf8'), requestsBefore = JSON.stringify(requests.list());
const profiles = new LineProfiles(store, 'test-oa', 'fixture-token-only', async () => new Response(JSON.stringify({ userId: lineUser, displayName: 'ชื่อ LINE จาก API จำลอง' })));
const server = createServer(adminHandler(monitor, requests, store, profiles));
let browser;
try {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = 'http://127.0.0.1:' + server.address().port;
  browser = await chromium.launch({ executablePath: process.env.CHROME_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  await page.goto(url + '/#customers');
  const panel = page.locator('#customers-panel'), dialog = panel.locator('dialog');
  const button = (scope, name) => scope.getByRole('button', { name, exact: true });
  async function save(label = 'บันทึก') {
    await button(dialog, label).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.getElementById('customers-state').textContent.startsWith('บันทึกแล้ว'));
  }
  assert.equal(await page.getByRole('tab').count(), 5);
  await button(panel, 'ชื่อ LINE จาก API จำลอง').click();
  await button(panel, 'แก้ไขข้อมูล').click();
  assert.ok((await dialog.textContent()).includes('ชื่อจาก LINE: ชื่อ LINE จาก API จำลอง'));
  assert.equal(await dialog.getByLabel('ชื่อที่ใช้เรียก', { exact: true }).inputValue(), '');
  await button(dialog, 'ยกเลิก').click();
  await button(panel, 'อัปเดตชื่อจาก LINE').click();
  await page.waitForFunction(() => document.getElementById('customers-state').textContent.startsWith('อัปเดตชื่อจาก LINE แล้ว'));
  await button(panel, '← กลับรายชื่อ').click();
  await button(panel, 'UI-fixture-only').click();
  await button(panel, 'แก้ไขข้อมูล').click();
  await dialog.getByLabel('ชื่อที่ใช้เรียก', { exact: true }).fill('ลูกค้าทดสอบ UI (ข้อมูลจำลองใน temp)');
  await dialog.getByLabel('อีเมล', { exact: true }).fill('fixture@example.invalid');
  await dialog.getByLabel('ที่มาของข้อมูล', { exact: true }).selectOption('ทีมตรวจสอบ');
  await dialog.getByLabel('อ้างอิงเพิ่มเติม (ถ้ามี)').fill('ชุดทดสอบเบราว์เซอร์');
  await save();
  await panel.getByRole('heading', { name: 'ลูกค้าทดสอบ UI (ข้อมูลจำลองใน temp)', exact: true }).waitFor();

  await button(panel, 'เพิ่มโน้ต').click();
  await dialog.getByLabel('ประเภทโน้ต', { exact: true }).selectOption('customer');
  await dialog.getByLabel('ข้อความโน้ต', { exact: true }).fill('<script>alert(1)</script> ข้อมูลที่ลูกค้าแจ้งสำหรับทดสอบ');
  await save();
  await panel.getByText('<script>alert(1)</script> ข้อมูลที่ลูกค้าแจ้งสำหรับทดสอบ', { exact: true }).waitFor();
  assert.equal(await panel.locator('script').count(), 0);
  await button(panel, 'แก้ไข').click();
  await dialog.getByLabel('ประเภทโน้ต', { exact: true }).selectOption('observation');
  await dialog.getByLabel('ข้อความโน้ต', { exact: true }).fill('ข้อสังเกตทีมในชุดทดสอบ');
  await save();
  await button(panel, 'ประวัติแก้ไข').click();
  assert.ok((await dialog.textContent()).includes('<script>alert(1)</script>'));
  await button(dialog, 'ปิด').click();

  await button(panel, 'จัดการแท็ก').click();
  await dialog.getByLabel('แท็กหนึ่งรายการต่อหนึ่งบรรทัด').fill('ทดสอบ AI\nทดสอบ Excel');
  await save();
  await button(panel, 'กลุ่มลูกค้า').click();
  await button(panel, 'สร้างกลุ่ม').click();
  await dialog.getByLabel('ชื่อกลุ่ม', { exact: true }).fill('กลุ่มทดสอบหนึ่ง');
  await save();
  await button(panel, 'สร้างกลุ่ม').click();
  await dialog.getByLabel('ชื่อกลุ่ม', { exact: true }).fill('กลุ่มทดสอบสอง');
  await save();
  await button(panel, 'รายชื่อลูกค้า').click();
  await button(panel, 'ลูกค้าทดสอบ UI (ข้อมูลจำลองใน temp)').click();
  await button(panel, 'จัดการกลุ่ม').click();
  await dialog.getByLabel('กลุ่มทดสอบหนึ่ง', { exact: true }).check();
  await dialog.getByLabel('กลุ่มทดสอบสอง', { exact: true }).check();
  await save();
  await panel.locator('#customers-content').getByText('กลุ่มทดสอบหนึ่ง', { exact: true }).waitFor();
  await button(panel, 'บันทึกสถานะ').click();
  await dialog.getByLabel('สถานะ', { exact: true }).selectOption('subscribed');
  await button(dialog, 'บันทึก').click();
  await dialog.getByRole('alert').filter({ hasText: 'กรุณากรอก' }).waitFor();
  await dialog.getByLabel('หลักฐานหรือข้อความอ้างอิง (จำเป็นเมื่อรับ/ไม่รับข่าวสาร)').fill('หลักฐานสมมติสำหรับชุดทดสอบใน temp เท่านั้น');
  await save();
  await button(panel, 'ดูประวัติสถานะ').click();
  assert.ok((await dialog.textContent()).includes('หลักฐานสมมติ'));
  await button(dialog, 'ปิด').click();

  // Conflict: another browser edits after the first browser opens a form.
  await button(panel, 'แก้ไขข้อมูล').click();
  await dialog.getByLabel('องค์กร', { exact: true }).fill('องค์กรจากฟอร์มค้าง');
  await dialog.getByLabel('ที่มาของข้อมูล', { exact: true }).selectOption('ทีมตรวจสอบ');
  const state = store.snapshot({ events: monitor.snapshot().events, requests: requests.list() });
  store.mutate({ revision: state.revision, action: 'tags.update', id: state.customers.find(c => c.identity.user === 'UI-fixture-only').id, data: { tags: ['เปลี่ยนระหว่างเปิดฟอร์ม'] } });
  await button(dialog, 'บันทึก').click();
  await dialog.getByRole('alert').filter({ hasText: 'ข้อมูลเปลี่ยนแล้ว' }).waitFor();
  assert.equal(await dialog.getByLabel('องค์กร', { exact: true }).inputValue(), 'องค์กรจากฟอร์มค้าง');
  await button(dialog, 'ตรวจเทียบแล้ว ใช้ข้อมูลที่กรอกกับฉบับล่าสุด').click();
  await save();

  const screenshots = resolve('design/customer-groups'); mkdirSync(screenshots, { recursive: true });
  await page.screenshot({ path: join(screenshots, 'implemented-profile-test-data.png'), fullPage: true });
  await button(panel, 'ดูบทสนทนา').click();
  await page.locator('#monitor-panel').waitFor({ state: 'visible' });
  assert.ok((await page.locator('#messages').textContent()).includes('ข้อความทดสอบใน temp เท่านั้น'));
  await page.getByRole('tab', { name: 'งานรอดูแล', exact: true }).click();
  await page.locator('#requests-rows').getByText('เรื่องทดสอบ UI ใน temp เท่านั้น', { exact: true }).waitFor();
  await page.getByRole('tab', { name: 'ลูกค้าและกลุ่ม', exact: true }).click();
  await button(panel, '← กลับรายชื่อ').click();
  const search = panel.getByLabel('ค้นหาชื่อ ข้อมูลติดต่อ แท็ก หรือรหัส');
  await search.fill('fixture@example.invalid');
  assert.equal(await panel.locator('tbody tr').count(), 1);
  await button(panel, 'ลูกค้าทดสอบ UI (ข้อมูลจำลองใน temp)').click();
  await button(panel, '← กลับรายชื่อ').click();
  assert.equal(await panel.getByLabel('ค้นหาชื่อ ข้อมูลติดต่อ แท็ก หรือรหัส').inputValue(), 'fixture@example.invalid');
  await button(panel, 'ล้างตัวกรอง').click();
  await button(panel, 'กลุ่มลูกค้า').click();
  const groupCard = panel.locator('.box').filter({ has: page.getByRole('heading', { name: 'กลุ่มทดสอบหนึ่ง', exact: true }) });
  await button(groupCard, 'เพิ่ม / นำสมาชิกออก').click();
  await dialog.getByLabel(/ลูกค้าทดสอบ UI/).uncheck();
  await dialog.getByLabel(/UI-second-only/).check();
  await save();
  await button(groupCard, 'ลบกลุ่ม').click();
  await save('ยืนยันลบกลุ่ม');
  assert.equal(await panel.getByRole('heading', { name: 'กลุ่มทดสอบหนึ่ง', exact: true }).count(), 0);
  await button(panel, 'รายชื่อลูกค้า').click();
  await button(panel, 'ลูกค้าทดสอบ UI (ข้อมูลจำลองใน temp)').click();
  await button(panel, 'ลบ').click();
  await save('ยืนยันลบโน้ต');
  await panel.getByText('ยังไม่มีโน้ตของลูกค้ารายนี้', { exact: true }).waitFor();
  await button(panel, 'โน้ตที่ลบแล้ว (1)').click();
  assert.ok((await dialog.textContent()).includes('ข้อสังเกตทีมในชุดทดสอบ'));
  await button(dialog, 'ปิด').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(screenshots, 'implemented-mobile-test-data.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.reload();
  await button(panel, 'ลูกค้าทดสอบ UI (ข้อมูลจำลองใน temp)').click();
  assert.ok((await panel.textContent()).includes('องค์กรจากฟอร์มค้าง'));
  assert.deepEqual(errors, []);
  assert.equal(readFileSync(join(root, 'monitor/monitor.json'), 'utf8'), monitorBefore);
  assert.equal(JSON.stringify(requests.list()), requestsBefore);
  const persisted = new CustomerStore(join(root, 'customers')).snapshot({ events: [], requests: [] });
  assert.equal(persisted.customers.length, 3);
  console.log('PASS: browser LINE name/refresh, profile/notes/tags/groups/consent/conflict/navigation/search/mobile/reload; original monitor and requests unchanged; no page errors. All writes used temp fixtures.');
} finally {
  if (browser) await browser.close();
  server.closeAllConnections(); await new Promise(resolve => server.close(resolve));
  rmSync(root, { recursive: true, force: true });
}
